// Package main содержит multichecker staticlint для статической проверки проекта.
//
// Запуск из корня репозитория:
//
//	go run ./cmd/staticlint ./...
//
// Альтернативный запуск через собранный бинарный файл:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// Multichecker объединяет несколько групп анализаторов.
//
// Стандартные анализаторы golang.org/x/tools/go/analysis/passes:
//
//   - appends проверяет некорректные вызовы append без использования результата.
//   - asmdecl проверяет соответствие Go-объявлений и ассемблерных функций.
//   - assign находит бесполезные присваивания.
//   - atomic проверяет распространённые ошибки использования sync/atomic.
//   - bools упрощает и проверяет подозрительные булевы выражения.
//   - buildtag проверяет корректность build tags.
//   - cgocall ищет запрещённые передачи Go-указателей в cgo.
//   - composite проверяет неименованные поля в composite literals внешних пакетов.
//   - copylock запрещает копирование значений, содержащих lock.
//   - deepequalerrors проверяет некорректное сравнение errors через reflect.DeepEqual.
//   - defers находит ошибки в defer, например defer time.Since(...).
//   - directive проверяет директивы компилятора и инструментов.
//   - errorsas проверяет второй аргумент errors.As.
//   - framepointer проверяет сохранение frame pointer в ассемблере.
//   - hostport проверяет корректную сборку адресов host:port.
//   - httpmux проверяет шаблоны путей net/http.ServeMux.
//   - httpresponse проверяет ошибки при работе с http.Response.
//   - ifaceassert находит невозможные type assertions между interface-типами.
//   - loopclosure проверяет захват переменных цикла в замыканиях.
//   - lostcancel проверяет потерянные cancel-функции context.WithCancel/Timeout.
//   - nilfunc находит бесполезные сравнения функций с nil.
//   - nilness выполняет анализ nil-значений и недостижимых веток.
//   - printf проверяет форматные строки и аргументы printf-подобных функций.
//   - reflectvaluecompare запрещает некорректное сравнение reflect.Value.
//   - shadow находит переменные, затеняющие внешние объявления.
//   - shift проверяет подозрительные битовые сдвиги.
//   - sigchanyzer проверяет ошибки с каналами os.Signal.
//   - slog проверяет корректность пар ключ-значение в log/slog.
//   - sortslice проверяет использование sort.Slice.
//   - stdmethods проверяет сигнатуры стандартных методов вроде String и Unmarshal.
//   - stdversion проверяет использование API относительно версии Go модуля.
//   - stringintconv проверяет подозрительные преобразования integer в string.
//   - structtag проверяет корректность struct tags.
//   - testinggoroutine проверяет вызовы Fatal из goroutine в тестах.
//   - tests проверяет распространённые ошибки в тестах.
//   - timeformat проверяет ошибочные шаблоны форматирования времени.
//   - unmarshal проверяет аргументы json.Unmarshal и похожих функций.
//   - unreachable находит недостижимый код.
//   - unsafeptr проверяет некорректные преобразования unsafe.Pointer.
//   - unusedresult проверяет проигнорированные результаты важных функций.
//   - unusedwrite находит записи в память, которые потом не читаются.
//   - waitgroup проверяет ошибки использования sync.WaitGroup.
//
// Анализаторы Staticcheck:
//
//   - Все анализаторы класса SA из honnef.co/go/tools/staticcheck. Они ищут
//     ошибки корректности: невозможные условия, неправильное использование API,
//     гонки с defer/loop, некорректную работу с nil, regexp, http, sync и другими
//     стандартными пакетами.
//   - ST1005 из класса ST проверяет стиль текстов ошибок: error string не должен
//     начинаться с заглавной буквы и заканчиваться пунктуацией без причины.
//
// Дополнительные публичные анализаторы:
//
//   - nilerr проверяет случаи, когда код возвращает nil вместо ненулевой ошибки
//     или наоборот.
//   - forcetypeassert запрещает небезопасные type assertions без проверки второго
//     результата.
//
// Собственный анализатор:
//
//   - noosexit запрещает прямой вызов os.Exit внутри функции main пакета main.
//     Такой вызов обходит defer и мешает корректному освобождению ресурсов.
